export function getLang() { return lang; }

export function setLang(next) {
  if (next !== 'de' && next !== 'en') return;
  lang = next;
  document.documentElement.lang = next;
  try { document.documentElement.dataset.lang = next; } catch {}
}

export function t(key, vars) {
  let str = DICT[lang]?.[key] ?? DICT.en?.[key] ?? DICT.de?.[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) str = str.replaceAll(`{${k}}`, String(v));
  }
  return str;
}

export function tx(value) {
  if (value == null) return '';
  if (typeof value === 'string') return value;
  return value[lang] ?? value.en ?? value.de ?? '';
}

export function hasKey(key) {
  return Boolean(DICT[lang]?.[key] || DICT.en?.[key]);
}

export function translationStats() {
  const de = Object.keys(DICT.de).length;
  const en = Object.keys(DICT.en).length;
  const missingEn = Object.keys(DICT.de).filter((k) => !DICT.en[k]);
  const missingDe = Object.keys(DICT.en).filter((k) => !DICT.de[k]);
  return { de, en, missingEn, missingDe };
}
